//! BCJ2 and the branch converters: archives must extract to the original bytes, and each
//! executable must get the converter its header calls for.

use std::fs;
use std::path::{Path, PathBuf};

use r7z::codec::{branch_for_image, describe_folder, Branch};
use r7z::format::sevenz::SevenZ;
use r7z::ops::bench::generate;
use r7z::ops::create::{create, CreateOptions, FilterMode, Item, NoProgress};
use r7z::ops::extract::{extract, Callbacks, ExtractOptions, Overwrite, Target};
use r7z::sevenz::read::ArchiveFile;

struct Quiet;
impl Callbacks for Quiet {}

fn tmp(name: &str) -> PathBuf {
    let d = std::env::temp_dir().join(format!("r7z-filters-{}-{name}", std::process::id()));
    let _ = fs::remove_dir_all(&d);
    fs::create_dir_all(&d).unwrap();
    d
}

/// A PE image header for the given COFF machine, followed by generated bytes.
fn pe(machine: u16, len: usize) -> Vec<u8> {
    let mut b = vec![0u8; len];
    b[..2].copy_from_slice(b"MZ");
    b[0x3C..0x40].copy_from_slice(&0x80u32.to_le_bytes());
    b[0x80..0x84].copy_from_slice(b"PE\0\0");
    b[0x84..0x86].copy_from_slice(&machine.to_le_bytes());
    let body = generate(len, machine as u64);
    b[0x200..].copy_from_slice(&body[0x200..]);
    b
}

/// An ELF header with the given class, byte order and machine, followed by generated bytes.
fn elf(bits64: bool, big: bool, machine: u16, len: usize) -> Vec<u8> {
    let mut b = generate(len, machine as u64);
    b[..4].copy_from_slice(b"\x7fELF");
    b[4] = if bits64 { 2 } else { 1 };
    b[5] = if big { 2 } else { 1 };
    let m = if big {
        machine.to_be_bytes()
    } else {
        machine.to_le_bytes()
    };
    b[18..20].copy_from_slice(&m);
    b
}

fn item(root: &Path, name: &str, data: &[u8]) -> Item {
    let src = root.join(name);
    fs::write(&src, data).unwrap();
    Item {
        src,
        name: name.to_string(),
        is_dir: false,
        size: data.len() as u64,
        mtime: Some(133_000_000_000_000_000),
        ctime: None,
        atime: None,
        attrib: Some(0x20),
    }
}

/// Extracts `arc` into `out` and checks every file against its source.
fn check_extract(arc: &Path, out: &Path, items: &[Item]) -> Vec<String> {
    let af = ArchiveFile::open(arc, None).unwrap();
    let eo = ExtractOptions {
        base: None,
        password: None,
        threads: 4,
        target: Target::Disk {
            dir: out.to_path_buf(),
            full_paths: true,
            overwrite: Overwrite::All,
        },
        selected: None,
    };
    let rep = extract(&SevenZ::new(af), &eo, &Quiet).unwrap();
    assert!(rep.errors.is_empty(), "{:?}", rep.errors);
    let mut differ = Vec::new();
    for it in items {
        if fs::read(&it.src).unwrap() != fs::read(out.join(&it.name)).unwrap() {
            differ.push(it.name.clone());
        }
    }
    differ
}

fn folder_methods(arc: &Path) -> Vec<String> {
    let af = ArchiveFile::open(arc, None).unwrap();
    af.archive
        .streams
        .folders
        .iter()
        .map(describe_folder)
        .collect()
}

#[test]
fn bcj2_round_trips_at_every_block_size() {
    let dir = tmp("bcj2");
    let mut data = generate(3 << 20, 3);
    data.extend_from_slice(&[0xE8, 0x10, 0x00, 0x00, 0x00].repeat(50_000));
    let items = vec![
        item(&dir, "a.exe", &data),
        item(&dir, "b.dll", &generate(700_000, 4)),
    ];
    for (label, block) in [("solid", None), ("groups", Some(1u64 << 20))] {
        let arc = dir.join(format!("{label}.7z"));
        let opts = CreateOptions {
            level: 9,
            filter: FilterMode::Bcj2,
            block_size: block,
            ..Default::default()
        };
        create(&arc, &items, &opts, &NoProgress).unwrap();
        assert!(
            folder_methods(&arc).iter().any(|m| m.ends_with("BCJ2")),
            "{label}: no BCJ2 folder"
        );
        let out = dir.join(format!("out-{label}"));
        assert!(check_extract(&arc, &out, &items).is_empty(), "{label}");
    }
}

#[test]
fn every_branch_converter_round_trips() {
    let dir = tmp("branch");
    let mut items = Vec::new();
    for b in Branch::ALL {
        let name = format!("{}.bin", b.name());
        items.push(item(&dir, &name, &generate(400_000, b.method())));
    }
    for b in Branch::ALL {
        let arc = dir.join(format!("{}.7z", b.name()));
        let file = format!("{}.bin", b.name());
        let one: Vec<Item> = items.iter().filter(|i| i.name == file).cloned().collect();
        let opts = CreateOptions {
            filter: FilterMode::Branch(b),
            ..Default::default()
        };
        create(&arc, &one, &opts, &NoProgress).unwrap();
        let out = dir.join(format!("out-{}", b.name()));
        assert!(check_extract(&arc, &out, &one).is_empty(), "{}", b.name());
    }
}

#[test]
fn file_type_picks_the_converter() {
    let dir = tmp("detect");
    let items = vec![
        item(&dir, "arm64.exe", &pe(0xAA64, 300_000)),
        item(&dir, "x86.dll", &pe(0x8664, 300_000)),
        item(&dir, "elf-arm.so", &elf(false, false, 40, 300_000)),
        item(&dir, "ppc.so", &elf(false, true, 20, 300_000)),
        // Not an executable name, so no converter whatever the header says.
        item(&dir, "data.bin", &pe(0x8664, 300_000)),
        // Executable name, but not an image.
        item(&dir, "notes.exe", &generate(300_000, 8)),
    ];
    let arc = dir.join("auto.7z");
    let opts = CreateOptions {
        level: 9,
        ..Default::default()
    };
    create(&arc, &items, &opts, &NoProgress).unwrap();
    let methods = folder_methods(&arc);
    // Methods are listed as space-separated coder names, e.g. "LZMA2:1m ARM64".
    let has = |token: &str| methods.iter().any(|m| m.split(' ').any(|t| t == token));
    assert!(has("ARM64"), "{methods:?}");
    assert!(has("BCJ2"), "{methods:?}");
    assert!(has("ARM"), "{methods:?}");
    assert!(has("PPC"), "{methods:?}");
    assert_eq!(
        methods
            .iter()
            .filter(|m| m.split(' ').any(|t| t == "ARM64"))
            .count(),
        1,
        "{methods:?}"
    );
    // data.bin and notes.exe get no converter.
    assert!(!has("BCJ"), "{methods:?}");
    let out = dir.join("out");
    assert!(check_extract(&arc, &out, &items).is_empty());
}

#[test]
fn header_probes_follow_the_formats() {
    assert_eq!(branch_for_image(&pe(0x8664, 512)), Some(Branch::X86));
    assert_eq!(branch_for_image(&pe(0x014C, 512)), Some(Branch::X86));
    assert_eq!(branch_for_image(&pe(0xAA64, 512)), Some(Branch::Arm64));
    assert_eq!(branch_for_image(&pe(0x01C4, 512)), Some(Branch::ArmThumb));
    assert_eq!(branch_for_image(&pe(0x0200, 512)), Some(Branch::Ia64));
    assert_eq!(branch_for_image(&pe(0x01C0, 512)), None);
    assert_eq!(
        branch_for_image(&elf(true, false, 62, 512)),
        Some(Branch::X86)
    );
    assert_eq!(
        branch_for_image(&elf(false, false, 40, 512)),
        Some(Branch::Arm)
    );
    assert_eq!(
        branch_for_image(&elf(true, false, 183, 512)),
        Some(Branch::Arm64)
    );
    assert_eq!(
        branch_for_image(&elf(false, true, 20, 512)),
        Some(Branch::Ppc)
    );
    assert_eq!(
        branch_for_image(&elf(true, true, 43, 512)),
        Some(Branch::Sparc)
    );
    assert_eq!(branch_for_image(&elf(true, false, 243, 512)), None);
    assert_eq!(branch_for_image(b"plain text"), None);
    assert_eq!(branch_for_image(&[]), None);
    // A truncated PE header must not panic.
    assert_eq!(branch_for_image(&b"MZ\x00\x00"[..]), None);
}

#[test]
fn branch_names_parse() {
    for b in Branch::ALL {
        assert_eq!(Branch::from_name(b.name()), Some(b));
        assert_eq!(Branch::from_name(&b.name().to_ascii_lowercase()), Some(b));
    }
    assert_eq!(Branch::from_name("zip"), None);
}
